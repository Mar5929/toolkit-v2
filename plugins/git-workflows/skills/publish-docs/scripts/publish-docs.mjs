#!/usr/bin/env node
// publish-docs: save Git-tracked project documents straight to the default
// branch from an isolated, sparse, detached worktree.
//
//   publish-docs.mjs start --branch <default-branch> -- <file> [more files]
//   publish-docs.mjs publish --message '<commit message>'
//
// `start` checks every path, fetches the default branch, creates a worktree
// beside the project, and prints its path. `publish` runs inside that worktree:
// it refuses staged paths outside the save, commits, pushes without force, and
// verifies that the remote has the commit.
//
// The save fetches and pushes `origin`; a repository with remotes but none
// named `origin` is refused at start, with the names it has. A repository with
// no remote (`git remote` prints nothing) has nothing to fetch or push. Then `start` bases the save on the local default branch, and
// `publish` commits and moves the local default branch forward with a
// fast-forward only (`git merge --ff-only` in the checkout that has the branch
// checked out, or a checked `git update-ref` when none has), and prints
// "No remote: committed locally."
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { dirname, basename, extname, join, resolve, isAbsolute } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

// Folders whose files are project documents, when their type is a document type.
// These and the files below follow the `paths` list of the project's
// .claude/rules/publish-project-documents.md rule.
export const DOCUMENT_FOLDERS = ['requirements/', 'system-guide/', 'ai-external-knowledge/', 'delivery/'];
// Project documents at the repository root.
export const ROOT_DOCUMENTS = ['DECISIONS.md', 'PROJECT.md', 'PROJECT-ROADMAP.md'];
// Single project documents outside those folders. The runbook exists only in
// Salesforce projects; the rest of tools/ is code.
export const OTHER_DOCUMENTS = ['tools/permissions/PERMISSIONS-RUNBOOK.md'];
// The only file types a documentation save accepts. Everything else (code,
// settings, JSON, spreadsheets, environment files) needs a worktree and a pull request.
export const DOCUMENT_EXTENSIONS = ['.md', '.txt', '.csv', '.xml', '.png', '.jpg', '.jpeg', '.gif', '.svg', '.pdf'];
// Salesforce data packages (loads and backups). They can hold production
// records and personal data, so only notes (.md) and .gitignore files are
// accepted here, whatever .gitignore says.
export const DATA_FOLDER = 'delivery/data/';
// Local, Git-ignored folders. Their saves go through the toolkit command.
export const LOCAL_FOLDERS = ['.memory/', '.work-items/'];
// Instruction files change agent behavior, so they need a pull request.
// Compared without regard to case: macOS treats agents.md and AGENTS.md as one file.
export const INSTRUCTION_FILES = ['AGENTS.md', 'CLAUDE.md', 'CLAUDE.local.md', 'SKILL.md'];
// Generated by `toolkit index knowledge`; saved together with the folder's files.
export const KNOWLEDGE_INDEX = 'ai-external-knowledge/INDEX.md';
// Folders every save workspace checks out, so links between documents can be checked.
export const SPARSE_BASE = ['requirements', 'system-guide', 'ai-external-knowledge'];

function git(cwd, args, { allowFailure = false } = {}) {
  const result = spawnSync('git', ['-C', cwd, ...args], { encoding: 'utf8' });
  if (result.error || (!allowFailure && result.status !== 0)) {
    // Some git commands (for example `diff --check`) print the reason on stdout.
    const detail = [result.stderr, result.stdout].map(text => (text || '').trim()).filter(Boolean).join('\n')
      || result.error?.message || `exit code ${result.status}`;
    throw new Error(`git ${args[0]} failed: ${detail}`);
  }
  return result;
}

function refuse(path, reason) {
  throw new Error(`Not a documentation save path: ${path} (${reason})`);
}

/** Returns the normalized project-relative path, or throws when it is not a document. */
export function cleanPath(path) {
  const value = String(path).replaceAll('\\', '/');
  if (!value || isAbsolute(path) || value.startsWith('/') || value.endsWith('/')
      || value.split('/').some(part => !part || part === '.' || part === '..')
      || value === '.git' || value.startsWith('.git/')) {
    throw new Error(`Expected a project-relative file path: ${path}`);
  }
  // Refusals compare without regard to case, so a differently cased name on a
  // case-insensitive disk (macOS, Windows) cannot slip past them.
  const lower = value.toLowerCase();
  const filename = basename(value);
  const lowerName = filename.toLowerCase();
  const extension = extname(lowerName);
  if (LOCAL_FOLDERS.some(folder => lower.startsWith(folder)))
    refuse(path, '.memory/ and .work-items/ are local and Git-ignored; save them with the toolkit command');
  if (INSTRUCTION_FILES.some(name => name.toLowerCase() === lowerName))
    refuse(path, 'instruction files change agent behavior; use a worktree and a pull request');
  const gitignoreInDelivery = lowerName === '.gitignore' && lower.startsWith('delivery/');
  if (value.split('/').some(part => part.startsWith('.')) && !gitignoreInDelivery)
    refuse(path, 'hidden files and folders, such as .env, are not documents');
  if (lower.startsWith(DATA_FOLDER) && extension !== '.md' && !gitignoreInDelivery)
    refuse(path, 'delivery/data/ holds load files and backups that can contain production records and personal data; only .md notes and .gitignore are saved from there');
  if (!DOCUMENT_EXTENSIONS.includes(extension) && !gitignoreInDelivery)
    refuse(path, `not a document file type; allowed: ${DOCUMENT_EXTENSIONS.join(', ')}. Code, settings, and data use a worktree and a pull request`);
  const inDocumentFolder = DOCUMENT_FOLDERS.some(folder => value.startsWith(folder));
  if (!inDocumentFolder && !ROOT_DOCUMENTS.includes(value) && !OTHER_DOCUMENTS.includes(value) && filename !== 'README.md')
    refuse(path, 'allowed: requirements/, system-guide/, ai-external-knowledge/, delivery/, DECISIONS.md, PROJECT.md, PROJECT-ROADMAP.md, tools/permissions/PERMISSIONS-RUNBOOK.md, README.md files');
  return value;
}

/** Adds the generated files a save of these paths must be allowed to stage. */
export function generatedPaths(paths) {
  const output = new Set(paths);
  if (paths.some(path => path.startsWith('ai-external-knowledge/') && path !== KNOWLEDGE_INDEX))
    output.add(KNOWLEDGE_INDEX);
  return [...output];
}

function refuseIgnored(source, paths) {
  for (const path of paths) {
    if (git(source, ['check-ignore', '-q', '--', path], { allowFailure: true }).status === 0)
      refuse(path, 'Git ignores it, so it is not a tracked document');
  }
}

function markerPath(cwd) {
  return join(git(cwd, ['rev-parse', '--absolute-git-dir']).stdout.trim(), 'toolkit-docsave.json');
}

function fetchDefault(cwd, branch) {
  const ref = `refs/remotes/origin/${branch}`;
  git(cwd, ['fetch', 'origin', `refs/heads/${branch}:${ref}`]);
  return git(cwd, ['rev-parse', ref]).stdout.trim();
}

/** The names of the repository's remotes, in the order `git remote` prints them. */
export function remoteNames(cwd) {
  return git(cwd, ['remote']).stdout.split('\n').map(name => name.trim()).filter(Boolean);
}

/** True when the repository has at least one remote. */
export function hasRemote(cwd) {
  return remoteNames(cwd).length > 0;
}

/**
 * The save fetches and pushes `origin` only. A repository whose remotes do not
 * include `origin` is refused at start with the names it has, so the save never
 * fails half way or is committed locally while a remote exists.
 */
export function checkOrigin(cwd, branch) {
  const remotes = remoteNames(cwd);
  if (remotes.length && !remotes.includes('origin'))
    throw new Error(`This repository has no remote named origin (its remotes: ${remotes.join(', ')}). publish-docs fetches and pushes origin only, so nothing was started. `
      + `Ask the owner which remote holds ${branch}; with his yes, rename it (git remote rename <name> origin) and run start again.`);
  return remotes.length > 0;
}

/** The commit the local branch points at, or an error that names the branch. */
function localBranchTip(cwd, branch) {
  const result = git(cwd, ['rev-parse', '--verify', '--quiet', `refs/heads/${branch}^{commit}`], { allowFailure: true });
  if (result.status !== 0 || !result.stdout.trim())
    throw new Error(`No remote, and there is no local branch ${branch}. Give the default branch with --branch.`);
  return result.stdout.trim();
}

function isAncestor(cwd, older, newer) {
  return git(cwd, ['merge-base', '--is-ancestor', older, newer], { allowFailure: true }).status === 0;
}

/** The worktree that has the branch checked out, or null when none has. */
export function worktreeHolding(cwd, branch) {
  const listing = git(cwd, ['worktree', 'list', '--porcelain']).stdout;
  let path = null;
  for (const line of listing.split('\n')) {
    if (line.startsWith('worktree ')) path = line.slice('worktree '.length);
    else if (line === `branch refs/heads/${branch}`) return path;
  }
  return null;
}

/**
 * No remote: move the local default branch forward to the save's commit, by
 * a fast-forward only. Returns nothing; throws with the next step on failure.
 */
function publishLocally(workspace, branch, head) {
  const current = localBranchTip(workspace, branch);
  if (current === head) return;
  if (!isAncestor(workspace, current, head))
    throw new Error(`The default branch ${branch} advanced. Bring this save workspace current (git rebase ${branch}, here only), regenerate any generated index, then run publish again.`);
  const holder = worktreeHolding(workspace, branch);
  if (holder) {
    const merged = git(holder, ['merge', '--ff-only', head], { allowFailure: true });
    if (merged.status !== 0) {
      const detail = [merged.stderr, merged.stdout].map(text => (text || '').trim()).filter(Boolean).join('\n');
      throw new Error(`Committed ${head} in this save workspace, but ${branch} could not be moved forward in ${holder}:\n${detail}\n`
        + 'When that checkout has this session\'s own uncommitted copy of a saved file, remove only that copy and run publish again: '
        + 'return a changed file to its committed state (git restore -- <file>); for a new file this session created there, delete that copy (rm <file>). '
        + 'Never discard another session\'s changes.');
    }
  } else {
    git(workspace, ['update-ref', `refs/heads/${branch}`, head, current]);
  }
  if (localBranchTip(workspace, branch) !== head)
    throw new Error(`Committed ${head}, but ${branch} does not point at it. Keep the workspace and inspect it.`);
}

function start(args) {
  const branchFlag = args.indexOf('--branch');
  const separator = args.indexOf('--');
  if (branchFlag < 0 || separator < 0 || branchFlag + 1 >= separator || separator === args.length - 1)
    throw new Error('Usage: publish-docs.mjs start --branch DEFAULT -- FILE...');
  const branch = args[branchFlag + 1];
  if (!/^[A-Za-z0-9][A-Za-z0-9._/-]*$/.test(branch) || branch.includes('..'))
    throw new Error('Invalid default branch name.');
  const source = git(process.cwd(), ['rev-parse', '--show-toplevel']).stdout.trim();
  if (existsSync(markerPath(source)))
    throw new Error('Already in an isolated save workspace. Continue that save instead of opening another.');
  const named = args.slice(separator + 1).map(cleanPath);
  refuseIgnored(source, named);
  const paths = generatedPaths(named);
  const local = !checkOrigin(source, branch);
  const base = local ? localBranchTip(source, branch) : fetchDefault(source, branch);
  const workspace = resolve(dirname(source), `${basename(source)}-docsave-${randomUUID().slice(0, 8)}`);
  if (existsSync(workspace)) throw new Error(`Save workspace already exists: ${workspace}`);
  git(source, ['worktree', 'add', '--no-checkout', '--detach', workspace, base]);
  const folders = new Set(SPARSE_BASE);
  for (const path of paths) {
    const folder = dirname(path).replaceAll('\\', '/');
    if (folder !== '.') folders.add(folder);
  }
  git(workspace, ['sparse-checkout', 'init', '--cone']);
  git(workspace, ['sparse-checkout', 'set', '--cone', ...folders]);
  git(workspace, ['read-tree', '-mu', 'HEAD']);
  writeFileSync(markerPath(workspace), JSON.stringify({ source, workspace, branch, base, paths, local }, null, 2));
  if (local) process.stderr.write(`No remote: this save will be committed locally on ${branch}; nothing is fetched or pushed.\n`);
  process.stdout.write(`${workspace}\n`);
}

function publish(args) {
  const messageFlag = args.indexOf('--message');
  if (messageFlag < 0 || !args[messageFlag + 1])
    throw new Error("Usage: publish-docs.mjs publish --message 'Commit message'");
  const workspace = git(process.cwd(), ['rev-parse', '--show-toplevel']).stdout.trim();
  const file = markerPath(workspace);
  if (!existsSync(file)) throw new Error('This is not a publish-docs save workspace. Run start first.');
  const state = JSON.parse(readFileSync(file, 'utf8'));
  const { source, branch, base, paths, local } = state;
  if (resolve(workspace) === resolve(source) || git(workspace, ['symbolic-ref', '-q', 'HEAD'], { allowFailure: true }).status === 0)
    throw new Error('Publication requires the isolated, detached save workspace.');
  const staged = git(workspace, ['diff', '--cached', '--name-only', '--no-renames', '-z']).stdout.split('\0').filter(Boolean);
  const allowed = new Set(paths);
  if (staged.some(path => !allowed.has(path)))
    throw new Error(`Other staged changes are present: ${staged.filter(path => !allowed.has(path)).join(', ')}`);
  const unstaged = git(workspace, ['diff', '--name-only', '--no-renames', '-z']).stdout.split('\0').filter(Boolean);
  const untracked = git(workspace, ['ls-files', '--others', '--exclude-standard', '-z']).stdout.split('\0').filter(Boolean);
  if (unstaged.length || untracked.length)
    throw new Error(`Unpublished files remain in this save workspace: ${[...unstaged, ...untracked].join(', ')}`);
  // Leftover conflict markers, blank lines at the end of a file, and a space
  // before a tab block the save. Trailing spaces do not: two of them are a
  // Markdown line break, which the scaffold's own templates use.
  const check = git(workspace, ['-c', 'core.whitespace=-blank-at-eol', 'diff', '--cached', '--check', '--no-color'], { allowFailure: true });
  if (check.status !== 0)
    throw new Error(`The staged files have conflict markers or whitespace errors:\n${[check.stdout, check.stderr].map(text => (text || '').trim()).filter(Boolean).join('\n')}`);
  if (staged.length) git(workspace, ['commit', '-m', args[messageFlag + 1]]);
  else if (git(workspace, ['rev-parse', 'HEAD']).stdout.trim() === (state.lastPublished || base))
    throw new Error('No changes to publish.');
  if (local) {
    const head = git(workspace, ['rev-parse', 'HEAD']).stdout.trim();
    publishLocally(workspace, branch, head);
    state.lastPublished = head;
    writeFileSync(file, JSON.stringify(state, null, 2));
    process.stdout.write(`No remote: committed locally. ${head} is on ${branch}.\n`);
    return;
  }
  const remote = fetchDefault(workspace, branch);
  if (git(workspace, ['merge-base', '--is-ancestor', remote, 'HEAD'], { allowFailure: true }).status !== 0)
    throw new Error('The default branch advanced. Bring this save workspace current, regenerate any generated index, then run publish again.');
  git(workspace, ['push', 'origin', `HEAD:${branch}`]);
  const verifiedRemote = fetchDefault(workspace, branch);
  const head = git(workspace, ['rev-parse', 'HEAD']).stdout.trim();
  if (git(workspace, ['merge-base', '--is-ancestor', head, verifiedRemote], { allowFailure: true }).status !== 0)
    throw new Error('Push returned, but the save could not be verified on the remote. Keep the workspace and inspect it.');
  state.lastPublished = head;
  writeFileSync(file, JSON.stringify(state, null, 2));
  process.stdout.write(`Published ${head} to origin/${branch}.\n`);
}

function main(argv) {
  try {
    const [command, ...args] = argv;
    if (command === 'start') start(args);
    else if (command === 'publish') publish(args);
    else throw new Error('Usage: publish-docs.mjs start --branch DEFAULT -- FILE... | publish --message TEXT');
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}

function isMain() {
  try {
    return Boolean(process.argv[1]) && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMain()) main(process.argv.slice(2));
