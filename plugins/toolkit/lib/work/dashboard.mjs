// .work-items/DASHBOARD.md: a generated view of the local tracker.
// Rebuilt after every change. Never edited by hand (the PreToolUse hook refuses it).
//
// Sections (ARCHITECTURE 4.3): waiting on the owner, in progress, ready,
// backlog, recently done, tree. Archived items are left out.

import { renderTable } from '../core/markdown.mjs';
import { stageShort, isTerminal, normalizeWaitingOn } from './lifecycle.mjs';
import { getLabel, isPlaceholder } from './model.mjs';
import { collectOwnerDecisions, collectAgentTodos } from './decisions.mjs';

const RECENT_LIMIT = 10;

function cell(value) {
  const v = value === null || value === undefined ? '' : String(value);
  return isPlaceholder(v) ? '' : v;
}

function byId(a, b) {
  return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
}

function nextAction(item) {
  return cell(getLabel(item.body || '', 'Next action', { section: 'Overview' }));
}

function table(headers, rows) {
  if (!rows.length) return '_None._\n';
  return renderTable(headers, rows);
}

/**
 * Build the tree lines: items under their parents, groups as folder names.
 * @param {Array} items every non-archived item with { id, meta, parent, group }
 * @returns {string[]} Markdown bullet lines
 */
export function treeLines(items, { bullet = '- ', indent = '  ', label } = {}) {
  const ids = new Set(items.map((i) => i.id));
  const kids = new Map();
  const roots = [];
  for (const it of [...items].sort(byId)) {
    const p = it.parent && it.parent !== 'none' && ids.has(it.parent) ? it.parent : null;
    if (p) {
      if (!kids.has(p)) kids.set(p, []);
      kids.get(p).push(it);
    } else {
      roots.push(it);
    }
  }
  const show = label || ((it) => `${it.id} ${it.meta.title || ''} (${isTerminal(it.meta.status) ? it.meta.status : `${stageShort(it.meta.stage)}, ${it.meta.status || 'no status'}`})`);
  const lines = [];
  const walk = (list, depth) => {
    // Items that sit in the same group folder are listed under that folder's name.
    const groups = new Map();
    const plain = [];
    for (const it of list) {
      const g = it.group || '';
      if (g) {
        if (!groups.has(g)) groups.set(g, []);
        groups.get(g).push(it);
      } else {
        plain.push(it);
      }
    }
    for (const it of plain) {
      lines.push(`${indent.repeat(depth)}${bullet}${show(it)}`);
      walk(kids.get(it.id) || [], depth + 1);
    }
    for (const [g, members] of [...groups.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
      lines.push(`${indent.repeat(depth)}${bullet}${g}/ (group)`);
      for (const it of members) {
        lines.push(`${indent.repeat(depth + 1)}${bullet}${show(it)}`);
        walk(kids.get(it.id) || [], depth + 2);
      }
    }
  };
  walk(roots, 0);
  return lines;
}

/**
 * The dashboard text.
 * @param {Array<{ id, meta, body, archived, parent, group, children }>} items
 * @param {{ ownerName?: string, unreadable?: Array<{ id?: string, location: string, message: string }> }} [opts]
 *   unreadable: record and design files that cannot be read; listed first when there are any.
 */
export function renderDashboard(items, { ownerName, unreadable = [] } = {}) {
  const live = items.filter((i) => !i.archived);
  const archivedCount = items.length - live.length;
  const decisions = collectOwnerDecisions(live, { ownerName });
  const agentTodos = collectAgentTodos(live, { ownerName });
  const inProgress = live.filter((i) => i.meta.status === 'In Progress' || i.meta.status === 'In Review').sort(byId);
  const ready = live.filter((i) => i.meta.status === 'Ready').sort(byId);
  const backlog = live.filter((i) => i.meta.status === 'Backlog').sort(byId);
  const done = live
    .filter((i) => isTerminal(i.meta.status))
    .sort((a, b) => (String(b.meta.updated || '') < String(a.meta.updated || '') ? -1 : String(b.meta.updated || '') > String(a.meta.updated || '') ? 1 : byId(a, b)))
    .slice(0, RECENT_LIMIT);
  const other = live.filter((i) => !['In Progress', 'In Review', 'Ready', 'Backlog'].includes(i.meta.status) && !isTerminal(i.meta.status)).sort(byId);

  const waitingText = (m) => {
    const w = normalizeWaitingOn(m.waiting_on);
    return w && w !== 'none' ? w : '';
  };

  const parts = [];
  parts.push('# Work items dashboard\n');
  parts.push('Generated by `toolkit work` after every change. Do not edit this file by hand; run `toolkit work sync` to rebuild it. Each item\'s WORK-ITEM.md is the record.\n');
  if (unreadable.length) {
    parts.push(`## Files that cannot be read\n\n${table(['ID', 'File', 'Problem'], unreadable.map((u) => [u.id || '', cell(u.location), cell(u.message)]))}`);
  }
  parts.push(`## Waiting on the owner\n\n${table(['ID', 'Title', 'What is needed', 'Continue with'], decisions.map((d) => [d.id, cell(d.title), d.what, d.continueWith]))}`);
  if (agentTodos.length) {
    parts.push(`## Agent to-do\n\n${table(['ID', 'Title', 'What the agent does next', 'Continue with'], agentTodos.map((d) => [d.id, cell(d.title), d.what, d.continueWith]))}`);
  }
  parts.push(`## In progress\n\n${table(['ID', 'Title', 'Stage', 'Status', 'Waiting on', 'Next action'], inProgress.map((i) => [i.id, cell(i.meta.title), stageShort(i.meta.stage), i.meta.status, waitingText(i.meta), nextAction(i)]))}`);
  parts.push(`## Ready\n\n${table(['ID', 'Title', 'Priority', 'Next action'], ready.map((i) => [i.id, cell(i.meta.title), cell(i.meta.priority), nextAction(i)]))}`);
  parts.push(`## Backlog\n\n${table(['ID', 'Title', 'Stage', 'Priority', 'Waiting on'], backlog.map((i) => [i.id, cell(i.meta.title), stageShort(i.meta.stage), cell(i.meta.priority), waitingText(i.meta)]))}`);
  if (other.length) {
    parts.push(`## Other status\n\n${table(['ID', 'Title', 'Stage', 'Status'], other.map((i) => [i.id, cell(i.meta.title), stageShort(i.meta.stage), cell(i.meta.status)]))}`);
  }
  parts.push(`## Recently done\n\n${table(['ID', 'Title', 'Status', 'Updated'], done.map((i) => [i.id, cell(i.meta.title), i.meta.status, cell(i.meta.updated)]))}`);
  const tree = treeLines(live);
  let treeText = tree.length ? `${tree.join('\n')}\n` : '_None._\n';
  if (archivedCount) treeText += `\n${archivedCount} archived item${archivedCount === 1 ? ' is' : 's are'} in archive/ and not shown.\n`;
  parts.push(`## Tree\n\n${treeText}`);
  return parts.join('\n');
}
