// ai-external-knowledge/INDEX.md: its table rows are built from each topic
// folder's SOURCE-RECORD.md (critique I16). Everything around the rows is kept
// as the file has it (the model's text when the project has no INDEX.md yet),
// and a project with no topic folders keeps the rows it has, so a new project
// keeps the model's file exactly.
//
// buildKnowledgeIndex(root, { pluginRoot }) -> { text, topics: [{ folder, title, publisher, captured, use, record }] }

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseFrontmatter } from '../core/frontmatter.mjs';

const PLUGIN_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

export const KNOWLEDGE_DIR = 'ai-external-knowledge';
export const INDEX_FILE = 'INDEX.md';
export const INDEX_TARGET = `${KNOWLEDGE_DIR}/${INDEX_FILE}`;
export const SOURCE_RECORD = 'SOURCE-RECORD.md';
export const TEMPLATE_FOLDER = 'topic-template';

const TABLE_HEADER = /^\|\s*Topic folder\s*\|/;

// Used only when neither the project nor the model has an INDEX.md with the topic table.
const HEAD = [
  '# Outside documentation index',
  '',
  "This folder holds captured public documentation from outside the project, one topic or source area per folder. This index is generated by `toolkit index knowledge` from each topic folder's `SOURCE-RECORD.md`; do not edit it by hand. `topic-template/` holds the templates for a new topic and is not listed.",
  '',
  '| Topic folder | Source and subject | Captured | When to consult it |',
  '| --- | --- | --- | --- |',
];

const FOOT = [
  '',
  'Captured material remains the source\'s writing. Project conclusions belong in requirements, designs, work items, or memory and should link back to the captured page. Do not place client files, meeting notes, project decisions, or agent instructions here.',
];

function isPlaceholder(value) {
  const v = String(value || '').trim();
  return !v || /^<[^>]*>\.?$/.test(v);
}

function cell(value) {
  return String(value || '').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|').trim();
}

/** "- Label: value" lines from a SOURCE-RECORD.md body. */
function labels(body) {
  const out = {};
  for (const line of body.split(/\r?\n/)) {
    const m = /^\s*-\s+([^:]+):\s*(.*)$/.exec(line);
    if (m && !(m[1].trim() in out)) out[m[1].trim()] = m[2].trim().replace(/\.$/, '');
  }
  return out;
}

/** The first paragraph under a "## <heading>" line. */
function sectionParagraph(body, heading) {
  const lines = body.split(/\r?\n/);
  const at = lines.findIndex((l) => l.trim().toLowerCase() === `## ${heading}`.toLowerCase());
  if (at === -1) return '';
  const para = [];
  for (let i = at + 1; i < lines.length; i++) {
    const l = lines[i];
    if (/^#{1,6} /.test(l)) break;
    if (!l.trim()) {
      if (para.length) break;
      continue;
    }
    para.push(l.trim());
  }
  return para.join(' ');
}

function describeTopic(root, folder) {
  const file = path.join(root, KNOWLEDGE_DIR, folder, SOURCE_RECORD);
  let text = null;
  try {
    text = fs.readFileSync(file, 'utf8');
  } catch {
    text = null;
  }
  if (text === null) {
    return { folder, title: null, publisher: null, captured: null, use: null, record: false };
  }
  let body = text;
  try {
    body = parseFrontmatter(text).body;
  } catch {
    body = text;
  }
  const h1 = (/^# (.+?)\s*$/m.exec(body) || [])[1] || null;
  const l = labels(body);
  const use = sectionParagraph(body, 'Project use');
  return {
    folder,
    title: isPlaceholder(h1) ? null : h1,
    publisher: isPlaceholder(l.Publisher) ? null : l.Publisher,
    url: isPlaceholder(l['Original documentation home']) ? null : l['Original documentation home'],
    captured: isPlaceholder(l['Captured on']) ? null : l['Captured on'],
    use: isPlaceholder(use) ? null : use,
    record: true,
  };
}

/** The topic folders: every folder in ai-external-knowledge/ except the template and hidden or "_" folders. */
export function topicFolders(root) {
  try {
    return fs.readdirSync(path.join(root, KNOWLEDGE_DIR), { withFileTypes: true })
      .filter((e) => e.isDirectory() && e.name !== TEMPLATE_FOLDER && !e.name.startsWith('.') && !e.name.startsWith('_'))
      .map((e) => e.name)
      .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  } catch {
    return [];
  }
}

/** The project's INDEX.md, or the model's when the project has none. */
function baseText(root, pluginRoot) {
  for (const file of [path.join(root, KNOWLEDGE_DIR, INDEX_FILE), path.join(pluginRoot, 'scaffold', 'model', KNOWLEDGE_DIR, INDEX_FILE)]) {
    try {
      return fs.readFileSync(file, 'utf8');
    } catch {
      // Try the next one.
    }
  }
  return null;
}

/** Replace the rows of the topic table in `text` (rows null: drop the folder rows only); null when it has no such table. */
function replaceRows(text, rows) {
  const lines = text.split('\n');
  const head = lines.findIndex((l) => TABLE_HEADER.test(l));
  if (head === -1 || !/^\|\s*-/.test(lines[head + 1] || '')) return null;
  let end = head + 2;
  while (end < lines.length && lines[end].trim().startsWith('|')) end += 1;
  const keep = rows || lines.slice(head + 2, end).filter((l) => !/^\|\s*\[/.test(l.trim()));
  return [...lines.slice(0, head + 2), ...keep, ...lines.slice(end)].join('\n');
}

export function buildKnowledgeIndex(root, { pluginRoot = PLUGIN_ROOT } = {}) {
  const topics = topicFolders(root).map((f) => describeTopic(root, f));
  const rows = topics.map((t) => {
    const folder = `[${t.folder}/](${encodeURI(t.folder)}/)`;
    if (!t.record) return `| ${folder} | No ${SOURCE_RECORD} yet | Not recorded | Not recorded |`;
    const subject = [t.publisher, t.title].filter(Boolean).join(': ') || 'Not recorded';
    return `| ${folder} | ${cell(subject)}${t.url ? ` (${cell(t.url)})` : ''} | ${cell(t.captured || 'Not recorded')} | ${cell(t.use || 'Not recorded')} |`;
  });
  const base = baseText(root, pluginRoot);
  if (base !== null) {
    if (!topics.length) {
      // No topic folders: rows that link to a folder are gone; other rows
      // (the model's placeholder row) stay.
      const text = replaceRows(base, null);
      if (text !== null) return { text, topics };
    } else {
      const text = replaceRows(base, rows);
      if (text !== null) return { text, topics };
    }
  }
  return { text: `${[...HEAD, ...rows, ...FOOT].join('\n')}\n`, topics };
}
